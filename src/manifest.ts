import { createHash } from "node:crypto"
import { Schema } from "effect"
import { StackConfig } from "./stack.ts"

/** sha256 hex, first 16 characters. */
export const hash = (content: string): string =>
  createHash("sha256").update(content).digest("hex").slice(0, 16)

export const EfforgeManifest = Schema.Struct({
  efforgeVersion: Schema.String,
  stack: StackConfig,
  command: Schema.String,
  /** overlay target -> hash(content) */
  files: Schema.Record(Schema.String, Schema.String),
})
export type EfforgeManifest = typeof EfforgeManifest.Type

export const manifestHeader = "// Generated by efforge. Used by `efforge add`.\n"

export const renderManifest = (m: EfforgeManifest): string =>
  `${manifestHeader}${JSON.stringify(m, null, 2)}\n`
