import { createHash } from "node:crypto"
import { Schema } from "effect"
import { StackConfig } from "./stack.ts"
import { efforgeVersion } from "./versions.ts"

/** sha256 hex, first 16 characters. */
export const hash = (content: string): string =>
  createHash("sha256").update(content).digest("hex").slice(0, 16)

/** The JSON Schema for efforge.jsonc, as shipped in the package version that wrote the file. */
export const manifestSchemaUrl = (version: string = efforgeVersion): string =>
  `https://unpkg.com/create-efforge@${version}/schemas/efforge.schema.json`

export const EfforgeManifest = Schema.Struct({
  $schema: Schema.optionalKey(Schema.String).annotate({
    description: "The JSON Schema for this file, for editors.",
  }),
  efforgeVersion: Schema.String.annotate({
    description: "The efforge version that created the project. `add` leaves it unchanged.",
  }),
  stack: StackConfig.annotate({
    description:
      "The stack choices. `efforge add` reads them and writes the new ones back. `npx create-efforge list --json` lists the ids.",
  }),
  command: Schema.String.annotate({
    description: "A non-interactive command that creates this stack again.",
  }),
  files: Schema.Record(Schema.String, Schema.String).annotate({
    description:
      "Template file -> hash of the content efforge wrote. `add` replaces a file only while its hash still matches. Internal: the hash format may change.",
  }),
}).annotate({
  title: "efforge.jsonc",
  description: "The stack of an efforge project, read and updated by `efforge add`.",
})
export type EfforgeManifest = typeof EfforgeManifest.Type

export const manifestHeader = "// Generated by efforge. Used by `efforge add`.\n"

/** `$schema` first, so editors see it; then the fields in schema order. */
export const renderManifest = (m: EfforgeManifest): string => {
  const { $schema, ...rest } = m
  return `${manifestHeader}${JSON.stringify($schema === undefined ? rest : { $schema, ...rest }, null, 2)}\n`
}
